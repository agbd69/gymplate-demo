import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { exerciseDataset } from "../../data/exercises.mjs";
import { foodDataset } from "../../data/foods.mjs";

const outDir = path.resolve(import.meta.dirname, "../supabase");
const outFile = path.join(outDir, "seed-open-data.sql");

function sql(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function number(value) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? String(parsed) : "0";
}

function json(value) {
  return `${sql(JSON.stringify(value ?? []))}::jsonb`;
}

const foodRows = foodDataset.map(food => `(${[
  sql(food.id),
  sql(food.name),
  number(food.calories),
  number(food.protein),
  number(food.carbs),
  number(food.fat),
  sql(food.unit),
  sql(food.category),
  sql(food.source)
].join(", ")})`);

const exerciseRows = exerciseDataset.map(exercise => `(${[
  sql(exercise.id),
  sql(exercise.name),
  sql(exercise.part),
  sql(exercise.equipment),
  sql(exercise.guide),
  json(exercise.steps),
  json(exercise.sets),
  sql(exercise.media?.gif || ""),
  sql(exercise.media?.thumbnail || ""),
  sql(exercise.source)
].join(", ")})`);

const content = `-- Generated by mvp/scripts/export-open-data-seed.mjs
-- Sources:
-- - Sanotsu/china-food-composition-data
-- - hasaneyldrm/exercises-dataset

insert into public.food_catalog
  (id, name, calories, protein, carbs, fat, unit, category, source)
values
${foodRows.join(",\n")}
on conflict (id) do update set
  name = excluded.name,
  calories = excluded.calories,
  protein = excluded.protein,
  carbs = excluded.carbs,
  fat = excluded.fat,
  unit = excluded.unit,
  category = excluded.category,
  source = excluded.source,
  updated_at = now();

insert into public.exercise_catalog
  (id, name, muscle_group, equipment, guide, steps, default_sets, gif_url, thumbnail_url, source)
values
${exerciseRows.join(",\n")}
on conflict (id) do update set
  name = excluded.name,
  muscle_group = excluded.muscle_group,
  equipment = excluded.equipment,
  guide = excluded.guide,
  steps = excluded.steps,
  default_sets = excluded.default_sets,
  gif_url = excluded.gif_url,
  thumbnail_url = excluded.thumbnail_url,
  source = excluded.source,
  updated_at = now();
`;

await mkdir(outDir, { recursive: true });
await writeFile(outFile, content, "utf8");
console.log(`Wrote ${foodDataset.length} foods and ${exerciseDataset.length} exercises to ${outFile}`);
